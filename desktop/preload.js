const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('beam', {
  state: () => ipcRenderer.invoke('state'),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onUi: (fn) => ipcRenderer.on('ui', (_e, m) => fn(m)),
  pathFor: (file) => webUtils.getPathForFile(file),
  sendPaths: (paths) => ipcRenderer.invoke('send-paths', paths),
  sendText: (text) => ipcRenderer.invoke('send-text', text),
  sendBlob: (name, mime, data) => ipcRenderer.invoke('send-blob', { name, mime, data }),
  paste: () => ipcRenderer.invoke('paste'),
  browse: () => ipcRenderer.invoke('browse'),
  item: (id, act) => ipcRenderer.invoke('item', { id, act }),
  dragOut: (id) => ipcRenderer.send('drag-out', id),
  setMode: (m) => ipcRenderer.invoke('set-mode', m),
  hide: () => ipcRenderer.invoke('hide'),
  pair: () => ipcRenderer.invoke('pair'),
  setTarget: (key) => ipcRenderer.invoke('set-target', key),
  invite: () => ipcRenderer.invoke('invite'),
  rename: (name) => ipcRenderer.invoke('rename', name),
  copyText: (text) => ipcRenderer.invoke('copy-text', text),
  setup: {
    info: () => ipcRenderer.invoke('setup:info'),
    check: (input) => ipcRenderer.invoke('setup:check', input),
    join: (input, name) => ipcRenderer.invoke('setup:join', { input, name }),
    startup: (on) => ipcRenderer.invoke('setup:startup', on),
    status: () => ipcRenderer.invoke('setup:status'),
    finish: () => ipcRenderer.invoke('setup:finish'),
    close: () => ipcRenderer.invoke('setup:close'),
  },
  setConfig: (patch) => ipcRenderer.invoke('set-config', patch),
  openInbox: () => ipcRenderer.invoke('open-inbox'),
  clearHistory: () => ipcRenderer.invoke('clear-history'),
  quit: () => ipcRenderer.invoke('quit'),
  checkUpdates: () => ipcRenderer.invoke('check-updates'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
});
